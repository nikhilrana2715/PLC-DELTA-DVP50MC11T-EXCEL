export function translate(key: string, lang: Lang): string {
  if (lang === 'en' || !key) return key
  const e = DICT[key]
  return e ? e[lang] : key
}

/** Non-hook translate using the current language (for one-off strings outside render). */
export function t(key: string): string {
  return translate(key, current)
}

/** Hook: returns a `t()` bound to the live language; re-renders the component on change. */
export function useT(): (key: string) => string {
  const lang = useSyncExternalStore(subscribe, getLang, getLang)
  return (key: string) => translate(key, lang)
}
